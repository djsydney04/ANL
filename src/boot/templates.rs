pub(super) fn entry(role: usize, function: usize, text: &mut Buffer) -> fmt::Result {
    let (symbol, setup) = match role {
        0 => (
            "anl_boot_entry",
            "    lla sp, __anl_boot_stack_top\n    andi sp, sp, -16\n",
        ),
        1 => (
            "anl_boot_hardware_entry",
            "    csrr a0, scause\n    csrr a1, sepc\n    csrr a2, stval\n    lla sp, __anl_terminal_stack_top\n    andi sp, sp, -16\n",
        ),
        2 => (
            "anl_boot_language_entry",
            "    andi a0, a0, 255\n    lla sp, __anl_terminal_stack_top\n    andi sp, sp, -16\n",
        ),
        _ => return Err(fmt::Error),
    };
    write!(
        text,
        ".section .text.{symbol},\"ax\",@progbits\n.balign 4\n.globl {symbol}\n.type {symbol},@function\n{symbol}:\n{setup}    tail anl_boot_f{function}\n.size {symbol}, .-{symbol}\n"
    )
}
