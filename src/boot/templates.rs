pub(super) fn header(profile: Profile, text: &mut Buffer) -> fmt::Result {
    match profile {
        Profile::V1 => text.write_str(HEADER),
        Profile::V2 => {
            text.write_str("/* Generated by ANL for rv64-virt-sbi-v2. */\n")?;
            text.write_str(HEADER.split_once('\n').ok_or(fmt::Error)?.1)
        }
        Profile::V3 => {
            text.write_str("/* Generated by ANL for rv64-virt-sbi-v3. */\n")?;
            text.write_str(HEADER.split_once('\n').ok_or(fmt::Error)?.1)
        }
    }
}

pub(super) fn primitive(p: &Primitive, text: &mut Buffer) -> fmt::Result {
    let id = p.id;
    match p.operation {
        Operation::Read8 {
            region: 0,
            offset: 5,
        } => write!(
            text,
            r#"static uint8_t anl_boot_f{id}(void) {{
    uint64_t value;
    __asm__ volatile ("lbu %0, 0(%1)" : "=r" (value) : "r" (UINT64_C(268435461)) : "memory");
    return (uint8_t)value;
}}
"#
        ),
        Operation::Write8 { region: 0, offset } if offset <= 4 => {
            let address = 268435456 + offset;
            write!(
                text,
                r#"static unsigned char anl_boot_f{id}(uint8_t value) {{
    __asm__ volatile ("sb %0, 0(%1)" : : "r" ((uint64_t)value), "r" (UINT64_C({address})) : "memory");
    return 0;
}}
"#
            )
        }
        Operation::Fence { region: 0 } => write!(
            text,
            r#"static unsigned char anl_boot_f{id}(void) {{
    __asm__ volatile ("fence iorw, iorw" : : : "memory");
    return 0;
}}
"#
        ),
        Operation::CsrClear {
            authority: 0,
            ref register,
            mask: 2,
        } if register == "sstatus" => write!(
            text,
            r#"static unsigned char anl_boot_f{id}(void) {{
    __asm__ volatile ("csrci sstatus, 2" : : : "memory");
    return 0;
}}
"#
        ),
        Operation::CsrWrite {
            authority: 0,
            ref register,
            value: 0,
        } if register == "sie" => write!(
            text,
            r#"static unsigned char anl_boot_f{id}(void) {{
    __asm__ volatile ("csrw sie, zero" : : : "memory");
    return 0;
}}
"#
        ),
        Operation::InstallTrap { authority: 0, .. } => write!(
            text,
            r#"static unsigned char anl_boot_f{id}(void) {{
    __asm__ volatile ("csrw stvec, %0" : : "r" (anl_boot_hardware_entry) : "memory");
    return 0;
}}
"#
        ),
        _ => Err(fmt::Error),
    }
}

// Only the checked v2 operation selects these out-of-line lowering helpers.
pub(super) fn illegal_declaration(id: usize, text: &mut Buffer) -> fmt::Result {
    writeln!(text, "extern unsigned char anl_boot_f{id}(void);")
}

pub(super) fn illegal_slot(id: usize, text: &mut Buffer) -> fmt::Result {
    write!(
        text,
        ".section .text.anl_boot_f{id},\"ax\",@progbits\n.balign 4\n.globl anl_boot_f{id}\n.type anl_boot_f{id},@function\nanl_boot_f{id}:\n    .4byte 0\n.size anl_boot_f{id}, .-anl_boot_f{id}\n"
    )
}

pub(super) const ASSEMBLY_HEADER: &str = ".option norelax\n.option norvc\n";
pub(super) fn entry(role: usize, function: usize, text: &mut Buffer) -> fmt::Result {
    let (symbol, setup) = match role {
        0 => (
            "anl_boot_entry",
            "    lla sp, __anl_boot_stack_top\n    andi sp, sp, -16\n",
        ),
        1 => (
            "anl_boot_hardware_entry",
            "    csrr a0, scause\n    csrr a1, sepc\n    csrr a2, stval\n    lla sp, __anl_terminal_stack_top\n    andi sp, sp, -16\n",
        ),
        2 => (
            "anl_boot_language_entry",
            "    andi a0, a0, 255\n    lla sp, __anl_terminal_stack_top\n    andi sp, sp, -16\n",
        ),
        _ => return Err(fmt::Error),
    };
    write!(
        text,
        ".section .text.{symbol},\"ax\",@progbits\n.balign 4\n.globl {symbol}\n.type {symbol},@function\n{symbol}:\n{setup}    tail anl_boot_f{function}\n.size {symbol}, .-{symbol}\n"
    )
}
